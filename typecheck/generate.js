// Writes runtime-api.ts, which reads every public member of the runtime API
// through lib/ipaddr.d.ts, so tsc fails when the definitions miss one.
import { writeFileSync } from 'node:fs';
import * as ipaddr from '../lib/ipaddr.js';

// Static helpers the classes use internally; not part of the public API.
const internal = new Set(['parser', 'SpecialRanges']);
const builtins = new Set(['length', 'name', 'prototype', 'constructor']);

const instances = {
    IPv4: { name: 'ipv4', sample: new ipaddr.IPv4([192, 0, 2, 1]) },
    // a zone ID, so the optional zoneId field is present
    IPv6: { name: 'ipv6', sample: ipaddr.IPv6.parse('fe80::1%eth0') },
};

const members = Object.keys(ipaddr).map((name) => `ipaddr.${name}`);

for (const [cls, { name, sample }] of Object.entries(instances)) {
    for (const key of Object.getOwnPropertyNames(ipaddr[cls])) {
        if (!builtins.has(key) && !internal.has(key)) {
            members.push(`ipaddr.${cls}.${key}`);
        }
    }

    const instanceKeys = [
        ...Object.getOwnPropertyNames(ipaddr[cls].prototype),
        ...Object.keys(sample),
    ];
    for (const key of instanceKeys) {
        if (!builtins.has(key)) {
            members.push(`${name}.${key}`);
        }
    }
}

writeFileSync(new URL('runtime-api.ts', import.meta.url), `// Generated by generate.js; do not edit.
import * as ipaddr from '../lib/ipaddr.js';

declare const ipv4: ipaddr.IPv4;
declare const ipv6: ipaddr.IPv6;

export const members = [
${members.map((member) => `    ${member},`).join('\n')}
];
`);
